// A tunnel that names another interface sends from the address that interface's
// declaration yields. systemd 257 cannot take it out of a delegated prefix itself, so
// regied resolves it from the delegation networkd holds and writes it into Local= as a
// literal; a prefix change rewrites the file (ADR 0022).
func TestDSLiteTunnelLocalAddressFromTheDelegation(t *testing.T) {
	cfg := load(t, tunnelOnLAN(`fromDelegatedPrefix: {interfaceRef: wan, subnetID: 1, token: "::1"}`))
	out := render(t, cfg, Runtime{DelegatedPrefixes: config.Delegations{
		"wan": {netip.MustParsePrefix("2001:db8:1000::/56")},
	}})

	if len(out.Warnings) != 0 {
		t.Errorf("warnings are %q, want none: naming another interface now does what it says", out.Warnings)
	}
	assertFile(t, out, "50-regied-dslite.netdev", `# Generated by regied from DSLiteTunnel/dslite. Do not edit.

[NetDev]
Name=dslite
Kind=ip6tnl
MTUBytes=1454

[Tunnel]
Mode=ipip6
Local=2001:db8:1000:1::1
Remote=2001:db8:ffff::1
TTL=64
EncapsulationLimit=none
`)
	// The dry-run shows the value and where it came from, as it shows the AFTR address.
	if len(out.Resolved) != 1 {
		t.Fatalf("resolved %q, want the tunnel's local address", out.Resolved)
	}
	for _, want := range []string{"DSLiteTunnel/dslite", "2001:db8:1000:1::1", "Interface/lan", "2001:db8:1000::/56"} {
		if !strings.Contains(out.Resolved[0], want) {
			t.Errorf("the resolved value %q does not mention %q", out.Resolved[0], want)
		}
	}
}

// The same declaration after the provider delegated another prefix renders the new
// address. Nothing in the declaration changed.
func TestDSLiteTunnelLocalAddressFollowsAPrefixChange(t *testing.T) {
	cfg := load(t, tunnelOnLAN(`fromDelegatedPrefix: {interfaceRef: wan, subnetID: 1, token: "::1"}`))
	before := fileNamed(t, render(t, cfg, Runtime{DelegatedPrefixes: config.Delegations{
		"wan": {netip.MustParsePrefix("2001:db8:1000::/56")},
	}}), "50-regied-dslite.netdev")
	after := fileNamed(t, render(t, cfg, Runtime{DelegatedPrefixes: config.Delegations{
		"wan": {netip.MustParsePrefix("2001:db8:2000:ab00::/56")},
	}}), "50-regied-dslite.netdev")

	if !strings.Contains(before, "Local=2001:db8:1000:1::1\n") {
		t.Errorf("before the change the tunnel does not send from the old delegation:\n%s", before)
	}
	if !strings.Contains(after, "Local=2001:db8:2000:ab01::1\n") {
		t.Errorf("after the change the tunnel does not send from the new delegation:\n%s", after)
	}
}

// A literal on the named interface is written as it is.
func TestDSLiteTunnelLocalAddressFromALiteralOnAnotherInterface(t *testing.T) {
	cfg := load(t, tunnelOnLAN(`"2001:db8:0:1::1/64"`))
	out := render(t, cfg, Runtime{})

	netdev := fileNamed(t, out, "50-regied-dslite.netdev")
	if !strings.Contains(netdev, "Local=2001:db8:0:1::1\n") {
		t.Errorf("the tunnel does not send from the literal on Interface/lan:\n%s", netdev)
	}
	if len(out.Warnings) != 0 {
		t.Errorf("warnings are %q, want none", out.Warnings)
	}
}

// With no delegation there is no address to send from. The tunnel's local address is part
// of what the link is, so its files are left exactly as an earlier turn wrote them, and
// the rendering says what it waits for (ADR 0021, ADR 0022).
func TestDSLiteTunnelWithoutADelegationIsLeftOut(t *testing.T) {
	cfg := load(t, tunnelOnLAN(`fromDelegatedPrefix: {interfaceRef: wan, subnetID: 1, token: "::1"}`))

	for name, delegations := range map[string]config.Delegations{
		"none": nil,
		"two": {"wan": {
			netip.MustParsePrefix("2001:db8:1000::/56"),
			netip.MustParsePrefix("2001:db8:2000::/56"),
		}},
		"a subnet that does not fit": {"wan": {netip.MustParsePrefix("2001:db8:1000::/64")}},
	} {
		t.Run(name, func(t *testing.T) {
			out := render(t, cfg, Runtime{DelegatedPrefixes: delegations})
			for _, file := range out.Files {
				if strings.HasPrefix(file.Name, "50-regied-dslite") {
					t.Errorf("%s was rendered without a local address:\n%s", file.Name, file.Content)
				}
			}
			if len(out.Omitted) != 1 {
				t.Fatalf("omitted %v, want exactly the tunnel", out.Omitted)
			}
			omitted := out.Omitted[0]
			if omitted.Resource != "DSLiteTunnel/dslite" || len(omitted.Files) != 2 {
				t.Errorf("the omission is %+v, want the tunnel's two files", omitted)
			}
			if !strings.Contains(omitted.Waiting, "Interface/wan") {
				t.Errorf("the omission does not name the interface it waits on: %q", omitted.Waiting)
			}
			// The rest of the host is rendered: the downstream link's address is
			// networkd's to derive, and it needs no value from this turn.
			fileNamed(t, out, "50-regied-lan.network")
		})
	}
}

// tunnelOnLAN is a router whose tunnel sends from the one IPv6 address of lan.
func tunnelOnLAN(address string) string {
	return `
    - kind: Interface
      metadata: {name: wan}
      spec:
        ifname: eth0
        dhcpv6:
          prefixDelegation:
            prefixLength: 56
    - kind: Interface
      metadata: {name: lan}
      spec:
        ifname: eth1
        addresses:
          - 192.168.10.1/24
          - ` + address + `
    - kind: DSLiteTunnel
      metadata: {name: dslite}
      spec:
        underlayRef: wan
        localAddressFrom:
          interfaceRef: lan
        aftrAddress: "2001:db8:ffff::1"
`
}

// A tunnel built from a name cannot be rendered before the name has been resolved, so it
// is not: neither the netdev nor the link's file, because half a tunnel is not a smaller
// tunnel. The rendering says what the tunnel waits for, and a later turn renders it once
// the name resolves (ADR 0016).
func TestDSLiteTunnelWithAnUnresolvedAFTRIsLeftOut(t *testing.T) {
	cfg := load(t, `
    - kind: Interface
      metadata: {name: wan}
      spec:
        ifname: eth0
    - kind: DSLiteTunnel
      metadata: {name: dslite}
      spec:
        underlayRef: wan
        localAddress: "2001:db8:0:ff::2"
        aftrHost: aftr.example.net
`)
	out := render(t, cfg, Runtime{})

	for _, file := range out.Files {
		if strings.HasPrefix(file.Name, "50-regied-dslite") {
			t.Errorf("%s was rendered without the AFTR's address:\n%s", file.Name, file.Content)
		}
	}
	if len(out.Omitted) != 1 {
		t.Fatalf("omitted %v, want exactly the tunnel", out.Omitted)
	}
	omitted := out.Omitted[0]
	if omitted.Resource != "DSLiteTunnel/dslite" {
		t.Errorf("the omission is attributed to %q, want DSLiteTunnel/dslite", omitted.Resource)
	}
	if len(omitted.Files) != 2 || omitted.Files[0] != "50-regied-dslite.netdev" || omitted.Files[1] != "50-regied-dslite.network" {
		t.Errorf("the omission names %v, want the tunnel's netdev and network files", omitted.Files)
	}
	if !strings.Contains(omitted.Waiting, "aftr.example.net") {
		t.Errorf("the omission does not name the host it waits for: %q", omitted.Waiting)
	}
	// The underlay still says the tunnel is stacked on it: that follows from the
	// declaration, not from the address, so it is not what changes when the name resolves.
	wan := fileNamed(t, out, "50-regied-wan.network")
	if !strings.Contains(wan, "Tunnel=dslite") {
		t.Errorf("the underlay lost its tunnel while the tunnel waits:\n%s", wan)
	}
}

// fileNamed is the content of one rendered file, or a failed test.
func fileNamed(t *testing.T, out *Output, name string) string {
	t.Helper()
	for _, file := range out.Files {
		if file.Name == name {
			return file.Content
		}
	}
	t.Fatalf("%s was not rendered", name)
	return ""
}

// A policy becomes a default route in a table of its own and a rule selecting that table
// by mark. Both go on the uplink the traffic leaves by, so that they follow it up and
// down.
func TestEgressRoutePolicyOnATunnel(t *testing.T) {
	cfg := load(t, `
    - kind: Interface
      metadata: {name: wan}
      spec:
        ifname: eth0
    - kind: DSLiteTunnel
      metadata: {name: dslite}
      spec:
        underlayRef: wan
        localAddress: "2001:db8:0:ff::2"
        aftrAddress: "2001:db8:ffff::1"
    - kind: EgressRoutePolicy
      metadata: {name: rest-via-dslite}
      spec:
        priority: 20
        egressRef: dslite
        sourceRanges: [192.0.2.0/24]
    - kind: EgressRoutePolicy
      metadata: {name: v6-via-dslite}
      spec:
        family: ipv6
        priority: 10
        egressRef: dslite
        sourceRanges: ["2001:db8:0:1::/64"]
        table: 42
`)
	out := render(t, cfg, Runtime{})

	assertFile(t, out, "50-regied-dslite.network", `# Generated by regied from DSLiteTunnel/dslite. Do not edit.

[Match]
Name=dslite

[Network]
LinkLocalAddressing=no
IPv6AcceptRA=no

[Route]
Destination=0.0.0.0/0
Metric=0

[Route]
Destination=0.0.0.0/0
Table=100

[RoutingPolicyRule]
Family=ipv4
FirewallMark=256
Table=100
Priority=100

[Route]
Destination=::/0
Table=42

[RoutingPolicyRule]
Family=ipv6
FirewallMark=257
Table=42
Priority=42
`)
}

// networkd does not create the PPPoE link and does not address it. The file regied
// writes for it carries the routing a policy needs and nothing else, and says so.
func TestEgressRoutePolicyOnAPPPoESession(t *testing.T) {
	cfg := load(t, `
    - kind: Interface
      metadata: {name: wan}
      spec:
        ifname: eth0
    - kind: PPPoESession
      metadata: {name: pppoe0}
      spec:
        interfaceRef: wan
        userIDFile: /etc/regied/secrets/pppoe-user-id
        passwordFile: /etc/regied/secrets/pppoe-password
    - kind: EgressRoutePolicy
      metadata: {name: upper-half-via-pppoe}
      spec:
        priority: 10
        egressRef: pppoe0
        sourceRanges: [192.0.2.128-192.0.2.255]
        mark: 4096
`)
	out := render(t, cfg, Runtime{})

	assertNames(t, out, "50-regied-pppoe0.network", "50-regied-wan.network")
	assertFile(t, out, "50-regied-pppoe0.network", `# Generated by regied from PPPoESession/pppoe0. Do not edit.
#
# pppd creates this link, names it and addresses it. regied writes this file only for
# the routes that leave by it: the static ones declared on the session, the table an
# EgressRoutePolicy needs, and the table a PortForward's replies go back by.
# KeepConfiguration keeps networkd from dropping what pppd installed.

[Match]
Name=pppoe0

[Network]
KeepConfiguration=yes

[Route]
Destination=0.0.0.0/0
Table=100

[RoutingPolicyRule]
Family=ipv4
FirewallMark=4096
Table=100
Priority=100
`)
}

