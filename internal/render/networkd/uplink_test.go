// A session's static routes are the same thing an Interface's are, and they go the same
// way: into the file this backend already writes for that link. pppd's option file
// cannot carry a route, so nothing else would install them.
func TestPPPoESessionRoutes(t *testing.T) {
	cfg := load(t, `
    - kind: Interface
      metadata: {name: wan}
      spec:
        ifname: eth0
    - kind: PPPoESession
      metadata: {name: pppoe0}
      spec:
        interfaceRef: wan
        userIDFile: /etc/regied/secrets/pppoe-user-id
        passwordFile: /etc/regied/secrets/pppoe-password
        routes:
          - destination: 198.51.100.0/24
            via: 192.0.2.1
          - destination: 203.0.113.0/24
`)
	out := render(t, cfg, Runtime{})

	assertNames(t, out, "50-regied-pppoe0.network", "50-regied-wan.network")
	assertFile(t, out, "50-regied-pppoe0.network", `# Generated by regied from PPPoESession/pppoe0. Do not edit.
#
# pppd creates this link, names it and addresses it. regied writes this file only for
# the routes that leave by it: the static ones declared on the session, and the table an
# EgressRoutePolicy needs. KeepConfiguration keeps networkd from dropping what pppd
# installed.

[Match]
Name=pppoe0

[Network]
KeepConfiguration=yes

[Route]
Destination=198.51.100.0/24
Gateway=192.0.2.1

[Route]
Destination=203.0.113.0/24
`)
}

