package networkd

import (
	"net/netip"
	"strings"
	"testing"

	"github.com/yuanying/regied/internal/config"
)

// derivedRoutes is a router that routes a subnet of its delegation to a host behind it,
// through that host's address on lan (ADR 0021).
const derivedRoutes = `
    - kind: Interface
      metadata: {name: wan}
      spec:
        ifname: eth0
        dhcpv6:
          prefixDelegation:
            prefixLength: 56
    - kind: Interface
      metadata: {name: lan}
      spec:
        ifname: eth1
        addresses:
          - 192.0.2.1/24
        routes:
          - destination: 172.16.0.0/16
            via: 192.0.2.10
          - destination:
              fromDelegatedPrefix: {interfaceRef: wan, subnetID: 2}
            via:
              fromDelegatedPrefix: {interfaceRef: wan, subnetID: 1, token: "::10"}
            metric: 50
          - destination:
              fromDelegatedPrefix: {interfaceRef: wan, subnetID: 3}
`

// A route's destination and next hop cut from the delegation are written into the
// .network as literals: the file is a function of the declaration and of the runtime
// values, and the turn rewrites it when the prefix changes (ADR 0021).
func TestDerivedRoutesAreWrittenAsTheValuesTheyResolveTo(t *testing.T) {
	out := render(t, load(t, derivedRoutes), Runtime{
		DelegatedPrefixes: config.Delegations{"wan": {netip.MustParsePrefix("2001:db8:1000::/56")}},
	})

	assertFile(t, out, "50-regied-lan.network", `# Generated by regied from Interface/lan. Do not edit.

[Match]
Name=eth1

[Network]
Address=192.0.2.1/24
IPv6AcceptRA=no

[Route]
Destination=172.16.0.0/16
Gateway=192.0.2.10

[Route]
Destination=2001:db8:1000:2::/64
Gateway=2001:db8:1000:1::10
Metric=50

[Route]
Destination=2001:db8:1000:3::/64
`)
	if len(out.Waiting) != 0 {
		t.Errorf("a rendering with the delegation waits for %q", out.Waiting)
	}
	resolved := strings.Join(out.Resolved, "\n")
	for _, want := range []string{
		"Interface/lan: spec.routes[1] to 2001:db8:1000:2::/64 via 2001:db8:1000:1::10, in 2001:db8:1000::/56 delegated on Interface/wan",
		"Interface/lan: spec.routes[2] to 2001:db8:1000:3::/64, in 2001:db8:1000::/56 delegated on Interface/wan",
	} {
		if !strings.Contains(resolved, want) {
			t.Errorf("the rendering does not say %q:\n%s", want, resolved)
		}
	}
}

// Without a delegation, the subnet a route names does not exist. The route is left out
// and the rest of the file is written as declared; the rendering says what it waits for
// (ADR 0021).
func TestADerivedRouteIsLeftOutWhileThereIsNoDelegation(t *testing.T) {
	out := render(t, load(t, derivedRoutes), Runtime{})

	assertFile(t, out, "50-regied-lan.network", `# Generated by regied from Interface/lan. Do not edit.

[Match]
Name=eth1

[Network]
Address=192.0.2.1/24
IPv6AcceptRA=no

[Route]
Destination=172.16.0.0/16
Gateway=192.0.2.10
`)
	if len(out.Omitted) != 0 {
		t.Errorf("a file was left out for want of the delegation: %+v", out.Omitted)
	}
	waiting := strings.Join(out.Waiting, "\n")
	for _, want := range []string{
		"Interface/lan: waiting for a delegated prefix on Interface/wan; spec.routes[1] is left out of 50-regied-lan.network",
		"Interface/lan: waiting for a delegated prefix on Interface/wan; spec.routes[2] is left out of 50-regied-lan.network",
	} {
		if !strings.Contains(waiting, want) {
			t.Errorf("the rendering does not say %q:\n%s", want, waiting)
		}
	}
}

// A subnet ID that does not fit in the delegation the provider handed out is waited for
// in the same way, with the reason (ADR 0021).
func TestADerivedRouteOutsideTheDelegationIsLeftOut(t *testing.T) {
	out := render(t, load(t, derivedRoutes), Runtime{
		DelegatedPrefixes: config.Delegations{"wan": {netip.MustParsePrefix("2001:db8:1000:ab00::/63")}},
	})
	waiting := strings.Join(out.Waiting, "\n")
	if !strings.Contains(waiting, "with room for subnetID 2") || !strings.Contains(waiting, "spec.routes[1]") {
		t.Errorf("the rendering does not say the subnet does not fit:\n%s", waiting)
	}
	content := fileContent(t, out, "50-regied-lan.network")
	if strings.Contains(content, "Metric=50") {
		t.Errorf("a route outside the delegation was written:\n%s", content)
	}
}

func fileContent(t *testing.T, out *Output, name string) string {
	t.Helper()
	for _, file := range out.Files {
		if file.Name == name {
			return file.Content
		}
	}
	t.Fatalf("no file %q among %v", name, names(out))
	return ""
}
