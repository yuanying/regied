// downstreamHost is a host behind a router: its LAN takes an address from the
// advertisement and declares the length of the delegation the advertised prefix belongs
// to, and its container bridge is cut from that delegation (ADR 0023).
const downstreamHost = `
    - kind: Interface
      metadata: {name: lan}
      spec:
        ifname: eth0
        addresses:
          - fromRouterAdvertisement: {token: "::151"}
        ipv6:
          advertisedDelegation: {prefixLength: 56}
    - kind: Interface
      metadata: {name: containers}
      spec:
        ifname: br-v6net
        bridge: {}
        addresses:
          - 172.20.0.1/16
          - fromDelegatedPrefix: {interfaceRef: lan, subnetID: 2, token: "::1"}
        routes:
          - destination:
              fromDelegatedPrefix: {interfaceRef: lan, subnetID: 3}
            via:
              fromDelegatedPrefix: {interfaceRef: lan, subnetID: 2, token: "::10"}
        ipv6:
          advertise: {mode: slaac}
`

var advertisedDelegation = Runtime{
	DelegatedPrefixes: config.Delegations{"lan": {netip.MustParsePrefix("2001:db8:0:100::/56")}},
}

// networkd has no delegation on a downstream host to derive from, so the bridge's address
// is written as the value it resolves to, and advertised as a literal prefix. The prefix is
// advertised with short lifetimes, so that containers drop the old one soon after a change:
// networkd does not announce a withdrawn prefix with a lifetime of zero (ADR 0023).
func TestADownstreamBridgeIsWrittenAsTheAddressItResolvesTo(t *testing.T) {
	out := render(t, load(t, downstreamHost), advertisedDelegation)

	assertFile(t, out, "50-regied-containers.network", `# Generated by regied from Interface/containers. Do not edit.

[Match]
Name=br-v6net

[Network]
ConfigureWithoutCarrier=yes
Address=172.20.0.1/16
Address=2001:db8:0:102::1/64
IPv6AcceptRA=no
IPv6SendRA=yes

[IPv6SendRA]
Managed=no
OtherInformation=no
EmitDNS=no

[IPv6Prefix]
Prefix=2001:db8:0:102::/64
PreferredLifetimeSec=1800
ValidLifetimeSec=3600

[Route]
Destination=2001:db8:0:103::/64
Gateway=2001:db8:0:102::10
`)
	if len(out.Waiting) != 0 {
		t.Errorf("a rendering with the delegation waits for %q", out.Waiting)
	}
	resolved := strings.Join(out.Resolved, "\n")
	want := "Interface/containers: spec.addresses[1] 2001:db8:0:102::1/64, in 2001:db8:0:100::/56 delegated on Interface/lan"
	if !strings.Contains(resolved, want) {
		t.Errorf("the rendering does not say %q:\n%s", want, resolved)
	}
}

// The LAN itself takes its address from the advertisement as before. Declaring the length
// of the delegation adds nothing to its file: it is what regied reads, not what networkd
// does.
func TestTheAdvertisedLANIsWrittenAsBefore(t *testing.T) {
	out := render(t, load(t, downstreamHost), advertisedDelegation)

	assertFile(t, out, "50-regied-lan.network", `# Generated by regied from Interface/lan. Do not edit.

[Match]
Name=eth0

[Network]
IPv6AcceptRA=yes

[IPv6AcceptRA]
Token=static:::151
`)
}

// Lifetimes written on the advertisement apply to a derived prefix as to a literal one.
func TestADownstreamPrefixTakesTheDeclaredLifetimes(t *testing.T) {
	cfg := load(t, strings.Replace(downstreamHost, "advertise: {mode: slaac}",
		"advertise: {mode: slaac, validLifetime: 2h}", 1))
	out := render(t, cfg, advertisedDelegation)

	content := fileContent(t, out, "50-regied-containers.network")
	if !strings.Contains(content, "PreferredLifetimeSec=3600\nValidLifetimeSec=7200\n") {
		t.Errorf("the declared lifetime is not applied:\n%s", content)
	}
	if len(out.Warnings) != 0 {
		t.Errorf("a lifetime that is applied is warned about: %v", out.Warnings)
	}
}

// Without an advertisement there is no delegation, and the bridge's derived address and
// its advertisement are left out: the subnet they name does not exist yet. The rest of
// the file is written, and the rendering says what it waits for (ADR 0021).
func TestADownstreamBridgeWaitsForTheAdvertisement(t *testing.T) {
	out := render(t, load(t, downstreamHost), Runtime{})

	assertFile(t, out, "50-regied-containers.network", `# Generated by regied from Interface/containers. Do not edit.

[Match]
Name=br-v6net

[Network]
ConfigureWithoutCarrier=yes
Address=172.20.0.1/16
IPv6AcceptRA=no
IPv6SendRA=yes

[IPv6SendRA]
Managed=no
OtherInformation=no
EmitDNS=no
`)
	waiting := strings.Join(out.Waiting, "\n")
	want := "Interface/containers: waiting for a delegated prefix on Interface/lan; spec.addresses[1] is left out of 50-regied-containers.network"
	if !strings.Contains(waiting, want) {
		t.Errorf("the rendering does not say %q:\n%s", want, waiting)
	}
}

