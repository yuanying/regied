// The .link file depends on nothing read at apply time, so a link whose DUID has not been
// read still gets it while its .network waits.
func TestInterfaceWakeOnLanDoesNotWaitForTheDUID(t *testing.T) {
	cfg := load(t, `
    - kind: Interface
      metadata: {name: wan}
      spec:
        ifname: eth0
        wakeOnLan: magic
        dhcpv6:
          prefixDelegation:
            prefixLength: 56
            duidFile: /etc/regied/duid
`)
	out := render(t, cfg, Runtime{})

	assertNames(t, out, "50-regied-wan.link")
	if len(out.Omitted) != 1 || !slices.Equal(out.Omitted[0].Files, []string{"50-regied-wan.network"}) {
		t.Errorf("want only the .network waiting for the DUID, got %+v", out.Omitted)
	}
}

