// An interface with addresses and an MTU is the simplest thing there is: one .network
// file, matched by kernel interface name.
func TestInterfaceAddressesAndMTU(t *testing.T) {
	cfg := load(t, `
    - kind: Interface
      metadata: {name: lab}
      spec:
        ifname: eth1
        mtu: 9000
        addresses:
          - 192.0.2.1/24
          - "2001:db8::1/64"
`)
	out := render(t, cfg, Runtime{})

	assertNames(t, out, "50-regied-lab.network")
	assertFile(t, out, "50-regied-lab.network", `# Generated by regied from Interface/lab. Do not edit.

[Match]
Name=eth1

[Link]
MTUBytes=9000

[Network]
Address=192.0.2.1/24
Address=2001:db8::1/64
IPv6AcceptRA=no
`)
}

// A bridge is a .netdev, a .network for the bridge itself, and one file per member that
// enslaves it. A member does not need an Interface resource of its own. The bridge is
// configured whether or not a member has link: its address is the segment's gateway,
// and no carrier on a bridge only means no client yet (ADR 0018).
func TestInterfaceBridge(t *testing.T) {
	cfg := load(t, `
    - kind: Interface
      metadata: {name: lan}
      spec:
        ifname: br-lan
        bridge:
          members: [eth1, eth2]
        addresses:
          - 192.0.2.1/24
`)
	out := render(t, cfg, Runtime{})

	assertNames(t, out,
		"50-regied-lan-eth1.network",
		"50-regied-lan-eth2.network",
		"50-regied-lan.netdev",
		"50-regied-lan.network",
	)
	assertFile(t, out, "50-regied-lan.netdev", `# Generated by regied from Interface/lan. Do not edit.

[NetDev]
Name=br-lan
Kind=bridge

[Bridge]
STP=no
VLANFiltering=no
`)
	assertFile(t, out, "50-regied-lan.network", `# Generated by regied from Interface/lan. Do not edit.

[Match]
Name=br-lan

[Network]
ConfigureWithoutCarrier=yes
Address=192.0.2.1/24
IPv6AcceptRA=no
`)
	assertFile(t, out, "50-regied-lan-eth1.network", `# Generated by regied from Interface/lan. Do not edit.

[Match]
Name=eth1

[Network]
LinkLocalAddressing=no
Bridge=br-lan
IPv6AcceptRA=no
`)
}

