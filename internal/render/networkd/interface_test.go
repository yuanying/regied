// The upstream interface runs the DHCPv6 client, and it runs it for the delegation
// alone: the interface's own global address comes from SLAAC. The DUID is read at apply
// time, and networkd wants its type and its payload apart.
func TestInterfacePrefixDelegationClient(t *testing.T) {
	cfg := load(t, `
    - kind: Interface
      metadata: {name: wan}
      spec:
        ifname: eth0
        dhcpv6:
          useDNS: false
          prefixDelegation:
            prefixLength: 56
            rapidCommit: true
            duidFile: /etc/regied/secrets/dhcpv6-duid
            iaid: 0
`)
	out := render(t, cfg, Runtime{DUIDs: map[string]string{
		"/etc/regied/secrets/dhcpv6-duid": "00:03:00:01:00:00:5e:00:53:01\n",
	}})

	assertFile(t, out, "50-regied-wan.network", `# Generated by regied from Interface/wan. Do not edit.

[Match]
Name=eth0

[Network]
DHCP=ipv6
IPv6AcceptRA=yes

[DHCPv6]
WithoutRA=solicit
UseAddress=yes
UseDNS=no
RapidCommit=yes
PrefixDelegationHint=::/56
DUIDType=link-layer
DUIDRawData=00:01:00:00:5e:00:53:01
IAID=0

[IPv6AcceptRA]
DHCPv6Client=always
UseDNS=no
`)
}

