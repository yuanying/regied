// Static routes leave by the link they are written on. A route with no next hop goes
// on-link through that interface.
// Wake-on-LAN goes in a .link file, which udev reads rather than networkd. It matches the
// declared name as OriginalName=, which is the name udev meets on the move event a rename
// sends (ADR 0020), and the apply engine is told which link each file is for.
func TestInterfaceWakeOnLan(t *testing.T) {
	cases := []struct {
		name, value, want string
	}{
		{"one mode", "magic", "magic"},
		{"a list", "[magic, unicast]", "magic unicast"},
		{"off", "off", "off"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			cfg := load(t, `
    - kind: Interface
      metadata: {name: lan}
      spec:
        ifname: eno1
        wakeOnLan: `+tc.value+`
        addresses:
          - 192.0.2.10/24
`)
			out := render(t, cfg, Runtime{})

			assertNames(t, out, "50-regied-lan.link", "50-regied-lan.network")
			assertFile(t, out, "50-regied-lan.link", `# Generated by regied from Interface/lan. Do not edit.

[Match]
OriginalName=eno1

[Link]
WakeOnLan=`+tc.want+`
`)
			want := []LinkFile{{Name: "50-regied-lan.link", Ifname: "eno1"}}
			if !slices.Equal(out.LinkFiles, want) {
				t.Errorf("the link files are %+v, want %+v", out.LinkFiles, want)
			}
		})
	}
}

